  /** Inputs for `self`, keyed by type or "Type.method". */
  private val selfGen: Map[String, String] = Map(
    "Quaternion" -> "P.quaternion(r)",
    "Basis.slerp" -> "P.basisRotation(r)",
    "Basis.get_euler" -> "P.basisRotation(r)",
    "Plane" -> "P.plane(r)",
    "Vector2i.aspect" -> "P.vector2iNonZero(r)"
  )

  private def selfFor(owner: String, method: String): String =
    selfGen.getOrElse(
      s"$owner.$method",
      selfGen.getOrElse(owner, gen(owner, owner, "", "self"))
    )

  /** The Scala type an engine value of Godot type `t` decodes to. */
  private def scalaType(t: String): String = t match {
    case "float"   => "Float"
    case "int"     => "Long"
    case "bool"    => "Boolean"
    case "String"  => "String"
    case "Variant" => "Option[Vector3]"
    case other     => other
  }

  private def decode(t: String, dyn: String): String = t match {
    case "Variant" => s"P.optVector3($dyn)"
    case other     => s"$dyn.as[${scalaType(other)}]"
  }

  private val unsupportedOpRight =
    Set(
      "Variant",
      "Dictionary",
      "Array",
      "PackedVector2Array",
      "PackedVector3Array",
      "PackedVector4Array",
      "PackedColorArray"
    )

  private val opCode = Map(
    "==" -> "Equal",
    "!=" -> "NotEqual",
    "<" -> "Less",
    "<=" -> "LessEqual",
    ">" -> "Greater",
    ">=" -> "GreaterEqual",
    "+" -> "Add",
    "-" -> "Subtract",
    "*" -> "Multiply",
    "/" -> "Divide",
    "%" -> "Module",
    "unary-" -> "Negate",
    "unary+" -> "Positive"
  )

  private val intVectors = Set("Vector2i", "Vector3i", "Vector4i")

  def parity(cls: ujson.Value): String = {
    val owner = cls("name").str
    val tests = Vector.newBuilder[(String, String)]

    // Methods.
    cls.obj.get("methods").map(_.arr.toVector).getOrElse(Vector.empty).foreach {
      m =>
        val name = m("name").str
        val isStatic = m.obj.get("is_static").exists(_.bool)
        val args =
          m.obj.get("arguments").map(_.arr.toVector).getOrElse(Vector.empty)
        val ret = m.obj.get("return_type").map(_.str).getOrElse("void")
        val argVals = args.zipWithIndex.map { case (a, i) =>
          s"    val a$i = ${gen(a("type").str, owner, name, a("name").str)}"
        }
        val argNames = args.indices.map(i => s"a$i")
        val scalaName = camel(name)
        val scalaCall =
          if (isStatic) s"$owner.$scalaName(${argNames.mkString(", ")})"
          else if (args.isEmpty) s"self.$scalaName"
          else s"self.$scalaName(${argNames.mkString(", ")})"
        val engineArgs = argNames.map(a => s", P.v($a)").mkString
        val engineCall =
          if (isStatic)
            s"""P.callStatic(P.v(P.sample$owner), "$name"$engineArgs)"""
          else s"""P.call(P.v(self), "$name"$engineArgs)"""
        val body =
          s"""  private def m_$name(r: P.Rng): String = {
           |    val self = ${selfFor(owner, name)}
           |${argVals.mkString("\n")}
           |    P.same("$owner.$name", $scalaCall, ${decode(ret, engineCall)})
           |  }""".stripMargin
        tests += (s"$owner.$name" -> body)
    }

    // Members.
    cls.obj.get("members").map(_.arr.toVector).getOrElse(Vector.empty).foreach {
      mem =>
        val name = mem("name").str
        val tpe = mem("type").str
        val body =
          s"""  private def p_$name(r: P.Rng): String = {
           |    val self = ${selfFor(owner, name)}
           |    P.same("$owner.$name", self.${camel(name)}, ${decode(
              tpe,
              s"""P.get(P.v(self), "$name")"""
            )})
           |  }""".stripMargin
        tests += (s"$owner.$name" -> body)
    }

    // Operators.
    cls.obj
      .get("operators")
      .map(_.arr.toVector)
      .getOrElse(Vector.empty)
      .zipWithIndex
      .foreach { case (op, i) =>
        val sym = op("name").str
        val right = op.obj.get("right_type").map(_.str)
        val ret = op("return_type").str
        if (
          opCode.contains(sym) && !right.exists(unsupportedOpRight.contains)
        ) {
          val unary = sym.startsWith("unary")
          val code = opCode(sym)
          val divides = sym == "/" || sym == "%"
          val rightGen = right.map {
            case "int"   => if (divides) "P.intNonZero(r)" else "P.int(r)"
            case "float" => if (divides) "P.floatNonZero(r)" else "P.float(r)"
            case t if divides && intVectors.contains(t) =>
              s"P.${t.head.toLower}${t.tail}NonZero(r)"
            case t => gen(t, owner, s"op$i", "rhs")
          }
          val rhsScala = right match {
            case Some("int") if intVectors.contains(owner) => "b.toInt"
            case Some("int")                               => "b.toFloat"
            case _                                         => "b"
          }
          val scalaExpr =
            if (unary) s"(${sym.stripPrefix("unary")}self)"
            else s"(self $sym $rhsScala)"
          val engineExpr =
            if (unary) s"P.op(P.Op.$code, P.v(self), P.nil)"
            else s"P.op(P.Op.$code, P.v(self), P.v(b))"
          val body =
            s"""  private def o_$i(r: P.Rng): String = {
               |    val self = ${selfFor(owner, s"op$i")}
               |${rightGen.map(g => s"    val b = $g").getOrElse("")}
               |    P.same("$owner $sym ${right.getOrElse(
                ""
              )}", $scalaExpr, ${decode(ret, engineExpr)})
               |  }""".stripMargin
          tests += (s"$owner $sym ${right.getOrElse("")}".trim -> body)
        }
      }

    val all = tests.result()
    val defs = all.map(_._2).mkString("\n\n")
    val names = all.map(_._2).map { b =>
      val n = b.linesIterator
        .next()
        .trim
        .stripPrefix("private def ")
        .takeWhile(_ != '(')
      n
    }
    val entries =
      all.zip(names).map { case ((label, _), fn) => s"""    "$label" -> $fn""" }
    s"""package game.harness
       |
       |// GENERATED by igen BuiltinGenerator from extension_api.json — do not edit.
       |
       |import gdext.builtin.*
       |import game.MathParityKit as P
       |
       |/** Scala-vs-engine checks for every `$owner` method, member and operator. */
       |object MathParity$owner {
       |  def checks: Seq[(String, P.Rng => String)] = Seq(
       |${entries.mkString(",\n")}
       |  )
       |
       |$defs
       |}
       |""".stripMargin
  }

  def parityIndex(types: Vector[String]): String =
    s"""package game.harness
       |
       |// GENERATED by igen BuiltinGenerator from extension_api.json — do not edit.
       |
       |import game.MathParityKit as P
       |
       |/** Every math parity check, by type. */
       |object MathParity {
       |  def checks: Seq[(String, P.Rng => String)] =
       |${types.map(t => s"    MathParity$t.checks").mkString(" ++\n")}
       |}
       |""".stripMargin

  private def writeFile(f: File, content: String): Unit = {
    f.getParentFile.mkdirs()
    val w = new FileWriter(f)
    try w.write(content)
    finally w.close()
  }
}
