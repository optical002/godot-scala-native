import java.io.{File, FileWriter}
import scala.io.Source

/** Generates the builtin-type sources that are pure data in
  * `extension_api.json`, plus the math parity harness.
  *
  *   - `gdext/builtin/BuiltinSizes.scala`: byte sizes for the `float_64` build.
  *   - `gdext/builtin/ColorNames.scala`: Godot's named colors.
  *   - `harness-scala/.../game/harness/MathParity*.scala`: for every method,
  *     operator and member of the math builtins, one check that runs the Scala
  *     implementation and the engine's own (through a Variant call) on random
  *     inputs and compares the results. It doubles as the coverage check: a
  *     method missing from the Scala library fails to compile here.
  *
  * The math implementations themselves are hand-written (ported from Godot's
  * `core/math`); the API dump has signatures, not bodies.
  */
object BuiltinGenerator {
  val mathTypes: Vector[String] = Vector(
    "Vector2",
    "Vector2i",
    "Rect2",
    "Rect2i",
    "Vector3",
    "Vector3i",
    "Transform2D",
    "Vector4",
    "Vector4i",
    "Plane",
    "Quaternion",
    "AABB",
    "Basis",
    "Transform3D",
    "Projection",
    "Color"
  )

  def run(
    jsonPath: String,
    builtinDir: String,
    harnessDir: String,
    godotDir: String
  ): Unit = {
    val src = Source.fromFile(new File(jsonPath))
    val json =
      try ujson.read(src.mkString)
      finally src.close()

    writeFile(new File(builtinDir, "BuiltinSizes.scala"), sizes(json))
    writeFile(new File(builtinDir, "ColorNames.scala"), colorNames(json))

    val classes =
      json("builtin_classes").arr.filter(c => mathTypes.contains(c("name").str))
    val perType = classes.map(c => c("name").str -> parity(c)).toVector
    perType.foreach { case (name, content) =>
      writeFile(new File(harnessDir, s"MathParity$name.scala"), content)
    }
    writeFile(
      new File(harnessDir, "MathParity.scala"),
      parityIndex(perType.map(_._1))
    )
    println(
      s"Generated builtin sizes, ${namedColorCount(json)} color names, " +
        s"and math parity checks for ${perType.size} types"
    )
  }

  // --- sizes / color names -------------------------------------------------

  def sizes(json: ujson.Value): String = {
    val cfg = json("builtin_class_sizes").arr
      .find(_("build_configuration").str == "float_64")
      .get("sizes")
      .arr
    val skip = Set("Nil", "bool", "int", "float", "Object")
    val lines = cfg.filterNot(s => skip.contains(s("name").str)).map { s =>
      s"  final val ${s("name").str} = ${s("size").num.toInt}"
    }
    s"""package gdext.builtin
       |
       |// GENERATED by igen BuiltinGenerator from extension_api.json — do not edit.
       |
       |/**
       | * Byte sizes of Godot's builtin (Variant) types for the `float_64` build
       | * configuration (Godot's default desktop build), from the API dump's
       | * `builtin_class_sizes`. These types are opaque blobs on the GDExtension
       | * boundary: the binding allocates exactly this many bytes and hands Godot a
       | * pointer, so a wrong size corrupts memory silently.
       | */
       |object BuiltinSizes {
       |${lines.mkString("\n")}
       |}
       |""".stripMargin
  }

  private def namedColorCount(json: ujson.Value): Int =
    json("builtin_classes").arr
      .find(_("name").str == "Color")
      .get("constants")
      .arr
      .size

  def colorNames(json: ujson.Value): String = {
    val consts = json("builtin_classes").arr
      .find(_("name").str == "Color")
      .get("constants")
      .arr
    val ColorRe = """Color\(([^,]+), ([^,]+), ([^,]+), ([^)]+)\)""".r
    def f(s: String) = {
      val v = s.trim;
      if (v.contains('.') || v.contains('e')) s"${v}f" else s"${v}f"
    }
    val vals = consts.map { c =>
      val ColorRe(r, g, b, a) = c("value").str: @unchecked
      s"  val ${c("name").str}: Color = Color(${f(r)}, ${f(g)}, ${f(b)}, ${f(a)})"
    }
    val map = consts.map(c =>
      s"""    "${c("name").str.replace("_", "")}" -> ${c("name").str}"""
    )
    s"""package gdext.builtin
       |
       |// GENERATED by igen BuiltinGenerator from extension_api.json — do not edit.
       |
       |/** Godot's named colors, reachable as `Color.RED`, `Color.ALICE_BLUE`, ... */
       |object ColorNames {
       |${vals.mkString("\n")}
       |
       |  /** Names without underscores, upper case (the `Color.fromString` lookup key). */
       |  private[builtin] lazy val byNormalizedName: Map[String, Color] = Map(
       |${map.mkString(",\n")}
       |  )
       |}
       |""".stripMargin
  }

  // --- parity harness ------------------------------------------------------

  private def camel(s: String): String = {
    val parts = s.split("_")
    (parts.head +: parts.tail.map(_.capitalize)).mkString
  }

  /** The kit generator producing a random value of a Godot type. */
  private def gen(
    tpe: String,
    owner: String,
    method: String,
    arg: String
  ): String = {
    val key = s"$owner.$method.$arg"
    special.get(key).orElse(special.get(s"*.$method.$arg")).getOrElse {
      tpe match {
        case "float" =>
          arg match {
            case "weight" | "t" | "amount"           => "P.unit(r)"
            case "angle"                             => "P.angle(r)"
            case "length" | "delta" | "mod" | "step" => "P.positive(r)"
            case "b_t"                               => "P.range(r, 0.5f, 1.5f)"
            case "pre_a_t"  => "P.range(r, -1.5f, -0.1f)"
            case "post_b_t" => "P.range(r, 1.6f, 3f)"
            case "aspect"   => "P.range(r, 0.5f, 2f)"
            case "z_near"   => "P.range(r, 0.05f, 1f)"
            case "z_far"    => "P.range(r, 10f, 500f)"
            case "size"     => "P.range(r, 0.5f, 20f)"
            case _          => "P.float(r)"
          }
        case "int"    => "P.int(r)"
        case "bool"   => "P.bool(r)"
        case "String" => "P.htmlCode(r)"
        case t        => s"P.${t.head.toLower}${t.tail}(r)"
      }
    }
  }

